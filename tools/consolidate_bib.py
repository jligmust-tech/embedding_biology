#!/usr/bin/env python3
"""Consolidate references.bib + every bib/*.bib into one canonical bibliography.

- Deduplicates entries by citation key.
- On conflicting metadata for the same key, keeps the entry with the most
  fields (tie-break: the one carrying a DOI) and records the conflict in
  verification/bib-conflicts.md for human review.
- Preserves every unique key; sorts output by key.
- Rewrites references.bib in place.

Usage:  python3 tools/consolidate_bib.py [--check]
        --check  report only, do not write.
"""
import re
import sys
import glob
import os
import collections

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAIN = os.path.join(ROOT, "references.bib")
FRAGS = sorted(glob.glob(os.path.join(ROOT, "bib", "*.bib")))
CONFLICTS = os.path.join(ROOT, "verification", "bib-conflicts.md")


def parse_entries(text, source):
    entries = []
    # split on an '@' that begins a line
    for block in re.split(r"(?m)^(?=@)", text):
        m = re.match(r"@(\w+)\s*\{\s*([^,\s]+)\s*,", block)
        if not m:
            continue
        entries.append((m.group(2), block.rstrip() + "\n", source))
    return entries


def norm(body):
    # normalize whitespace and case for comparison
    return re.sub(r"\s+", " ", body).strip().lower()


def field_count(body):
    return len(re.findall(r"(?m)^\s*\w+\s*=", body))


def has_doi(body):
    return "doi" in body.lower()


def main():
    check = "--check" in sys.argv
    seen = {}
    conflicts = collections.defaultdict(list)

    sources = [(MAIN, "references.bib")] + [(f, "bib/" + os.path.basename(f)) for f in FRAGS]
    for path, label in sources:
        if not os.path.exists(path):
            continue
        for key, body, src in parse_entries(open(path).read(), label):
            if key not in seen:
                seen[key] = (body, src)
            else:
                prev_body, prev_src = seen[key]
                if norm(prev_body) != norm(body):
                    conflicts[key].append((prev_src, prev_body, src, body))
                    # keep the richer entry
                    better = body if (field_count(body), has_doi(body)) > (field_count(prev_body), has_doi(prev_body)) else prev_body
                    seen[key] = (better, src)

    print("consolidated keys:", len(seen))
    print("conflicting keys:", len(conflicts))

    if conflicts and not check:
        os.makedirs(os.path.dirname(CONFLICTS), exist_ok=True)
        with open(CONFLICTS, "w") as out:
            out.write("# Bibliography conflicts\n\n")
            out.write("Same citation key defined with differing metadata across fragments.\n")
            out.write("The richer entry was kept; please confirm the canonical one.\n\n")
            for key, pairs in sorted(conflicts.items()):
                out.write("## `%s`\n\n" % key)
                for prev_src, prev_body, src, body in pairs:
                    out.write("**kept from richer source** (candidates: %s, %s)\n\n" % (prev_src, src))
                    out.write("```\n%s\n```\n\n" % prev_body.strip())
                    out.write("```\n%s\n```\n\n" % body.strip())
        print("wrote", os.path.relpath(CONFLICTS, ROOT))

    if check:
        return

    with open(MAIN, "w") as out:
        out.write("% Embeddings in Biology — canonical consolidated bibliography\n")
        out.write("% Generated by tools/consolidate_bib.py from references.bib + bib/*.bib\n\n")
        for key in sorted(seen):
            out.write(seen[key][0].rstrip() + "\n\n")
    print("wrote", os.path.relpath(MAIN, ROOT))


if __name__ == "__main__":
    main()
